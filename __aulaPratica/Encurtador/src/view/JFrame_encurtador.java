    private void jButton_testarWebActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton_testarWebActionPerformed
        String urlStr = jTextField_linkEncurtado.getText();
        if (!urlStr.isEmpty()) {
            try {
                // Adiciona "https://" caso o usuário digite apenas o domínio (ex: google.com)
                if (!urlStr.startsWith("http://") && !urlStr.startsWith("https://")) {
                    urlStr = "https://" + urlStr;
                }

                URI uri = new URI(urlStr);
                Desktop.getDesktop().browse(uri);
            } catch (IOException | URISyntaxException ex) {
                ex.printStackTrace();
                // Opcional: exiba um JOptionPane.showMessageDialog informando que o link é inválido
            }
        }
    }//GEN-LAST:event_jButton_testarWebActionPerformed

    private void jButton_gerarLinkEncurtadoActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton_gerarLinkEncurtadoActionPerformed
        String urlStr = jTextField_linkOriginal.getText();
        if (urlStr.isEmpty() || !ValidadorUrl.isLinkValido(urlStr)) {
            JOptionPane.showMessageDialog(this, "Verifique link informado", "Atenção", HEIGHT);
            return;
        }
        
        jTextField_linkEncurtado.setText( Encurtador.encurtar(urlStr, meusLinks) );
        
    }//GEN-LAST:event_jButton_gerarLinkEncurtadoActionPerformed

    private void jButton_limparActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton_limparActionPerformed
        jTextField_linkEncurtado.setText("");
        jTextField_linkOriginal.setText("");
    }//GEN-LAST:event_jButton_limparActionPerformed

    private void jButton_testarLocalActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton_testarLocalActionPerformed
        String urlStr = jTextField_linkEncurtado.getText();
        String urlOriginal;
        if (!urlStr.isEmpty()) {
            urlOriginal = Encurtador.buscarLinkEncurtado(urlStr, meusLinks);
            JOptionPane.showMessageDialog(this, urlOriginal);
        }
        
    }//GEN-LAST:event_jButton_testarLocalActionPerformed

