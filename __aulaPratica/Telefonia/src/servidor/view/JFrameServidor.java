    private void jButtonCarregarArquivoActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButtonCarregarArquivoActionPerformed
        StringBuilder dadosSessoes = new StringBuilder();
        if (jTextFieldNomeArquivo.getText().equals("")) {
            JOptionPane.showMessageDialog(this, "Você precisa informar o\n"
                    + "caminho e nome do arquivo\n"
                    + "da base de dados");
            return ;
        }
        if (!Utilidades.carregarArquivoEmHashMap(jTextFieldNomeArquivo.getText(), tabela.sessoes, dadosSessoes)) {
            JOptionPane.showMessageDialog(this, "Arquivo não localizado ou\n"
                    + "com problemas");
            return ;
        }
        jTextAreaDadosSessoes.setText(dadosSessoes.toString());
        
        
    }//GEN-LAST:event_jButtonCarregarArquivoActionPerformed

